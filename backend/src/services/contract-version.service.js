const { getPool } = require('../config/database');
const contractVersionRepository = require('../data/contract-version.repository');
const contractPdfStorage = require('../utils/contract-pdf-storage');
const { logError } = require('../utils/logger');

const FILE_FIELDS = ['file_name', 'mime_type', 'file_size', 'storage_path', 'file_hash'];
const STRING_LIMITS = {
  version_label: 50,
  file_name: 255,
  mime_type: 100,
  storage_path: 1000,
};
function createValidationError(fields) {
  const error = new Error('Validation failed');
  error.statusCode = 400;
  error.code = 'VALIDATION_ERROR';
  error.fields = fields;
  return error;
}

function createNotFoundError() {
  const error = new Error('Contract version not found');
  error.statusCode = 404;
  error.code = 'CONTRACT_VERSION_NOT_FOUND';
  return error;
}

function createConflictError(code, message) {
  const error = new Error(message);
  error.statusCode = 409;
  error.code = code;
  return error;
}

function normalizeVersionId(value) {
  const versionId = Number(value);
  if (!Number.isInteger(versionId) || versionId <= 0) {
    throw createNotFoundError();
  }
  return versionId;
}

function normalizeContractVersion(row) {
  if (!row) {
    return null;
  }
  return {
    ...row,
    is_referenced: Boolean(row.is_referenced),
  };
}

function normalizeEditablePayload(payload = {}) {
  const normalized = {};
  const errors = {};

  if (payload.version_label !== undefined) {
    const label = payload.version_label === null ? '' : String(payload.version_label).trim();
    if (!label) {
      errors.version_label = 'Version label is required';
    } else if (label.length > STRING_LIMITS.version_label) {
      errors.version_label = `Version label must be ${STRING_LIMITS.version_label} characters or less`;
    } else {
      normalized.version_label = label;
    }
  }

  for (const [field, maximumLength] of Object.entries(STRING_LIMITS)) {
    if (field === 'version_label' || payload[field] === undefined) {
      continue;
    }

    const value = payload[field] === null ? null : String(payload[field]).trim();
    if (value !== null && value.length > maximumLength) {
      errors[field] = `${field} must be ${maximumLength} characters or less`;
      continue;
    }
    normalized[field] = value || null;
  }

  for (const field of FILE_FIELDS) {
    if (payload[field] !== undefined) {
      errors[field] = 'PDF metadata is generated by the server during upload';
    }
  }

  return { normalized, errors };
}

function validateStatusFields(payload, { creating = false } = {}) {
  const errors = {};
  if (payload.status !== undefined && !(creating && payload.status === 'DRAFT')) {
    errors.status = creating
      ? 'New contract versions must be created as DRAFT'
      : 'Status can only be changed through the publish action';
  }
  if (payload.is_current !== undefined) {
    errors.is_current = 'Current status can only be changed through the current action';
  }
  return errors;
}

function validatePublishMetadata(version) {
  const errors = {};
  for (const field of FILE_FIELDS) {
    if (version[field] === null || version[field] === undefined || version[field] === '') {
      errors[field] = 'Contract PDF metadata is required before publishing';
    }
  }
  if (version.file_size !== null && Number(version.file_size) <= 0) {
    errors.file_size = 'Contract PDF file size must be greater than zero';
  }
  return errors;
}

async function withTransaction(handler) {
  const connection = await getPool().getConnection();
  try {
    await connection.beginTransaction();
    const result = await handler(connection);
    await connection.commit();
    return result;
  } catch (error) {
    await connection.rollback();
    throw error;
  } finally {
    connection.release();
  }
}

function mapDuplicateLabelError(error) {
  if (error.code === 'ER_DUP_ENTRY'
      && /uq_contract_versions_(?:version_label|shop_label)/.test(String(error.message))) {
    return createConflictError('CONTRACT_VERSION_LABEL_EXISTS', 'Version label already exists');
  }
  return error;
}

async function listContractVersions() {
  return { contract_versions: await contractVersionRepository.listContractVersions() };
}

async function getContractVersion(versionId) {
  const normalizedId = normalizeVersionId(versionId);
  const contractVersion = await contractVersionRepository.getContractVersionById(normalizedId);
  if (!contractVersion) {
    throw createNotFoundError();
  }
  return { contract_version: normalizeContractVersion(contractVersion) };
}

async function createDraft(payload = {}) {
  const { normalized, errors } = normalizeEditablePayload(payload);
  Object.assign(errors, validateStatusFields(payload, { creating: true }));
  const serviceType = payload.service_type === undefined
    ? 'GENERAL'
    : String(payload.service_type).trim().toUpperCase();
  if (!['GENERAL', 'GROOMING', 'BOARDING'].includes(serviceType)) {
    errors.service_type = 'Service type must be GENERAL, GROOMING, or BOARDING';
  } else {
    normalized.service_type = serviceType;
  }
  if (!normalized.version_label) {
    errors.version_label = 'Version label is required';
  }
  if (Object.keys(errors).length) {
    throw createValidationError(errors);
  }

  try {
    const versionId = await contractVersionRepository.createDraft(normalized);
    return getContractVersion(versionId);
  } catch (error) {
    throw mapDuplicateLabelError(error);
  }
}

async function updateDraft(versionId, payload = {}) {
  const normalizedId = normalizeVersionId(versionId);
  const { normalized, errors } = normalizeEditablePayload(payload);
  Object.assign(errors, validateStatusFields(payload));
  if (payload.service_type !== undefined) {
    errors.service_type = 'Service type cannot be changed after creation';
  }
  if (!Object.keys(normalized).length && !Object.keys(errors).length) {
    errors.version_label = 'At least one editable field is required';
  }
  if (Object.keys(errors).length) {
    throw createValidationError(errors);
  }

  try {
    return await withTransaction(async (connection) => {
      const existing = await contractVersionRepository.getContractVersionById(normalizedId, connection, true);
      if (!existing) {
        throw createNotFoundError();
      }
      if (existing.status !== 'DRAFT' || existing.is_current) {
        throw createValidationError({ status: 'Published contract versions cannot be edited' });
      }

      const updated = await contractVersionRepository.updateDraft(normalizedId, normalized, connection);
      if (!updated) {
        throw createNotFoundError();
      }
      return { contract_version: normalizeContractVersion(updated) };
    });
  } catch (error) {
    throw mapDuplicateLabelError(error);
  }
}

async function uploadDraftPdf(versionId, uploadedFile) {
  const normalizedId = normalizeVersionId(versionId);
  let metadata;
  let storageKey;
  let finalFileCreated = false;
  let commitAttempted = false;
  let committed = false;
  let previousStorageKey;
  let connection;
  let storageLockAcquired = false;

  try {
    metadata = await contractPdfStorage.inspectUploadedFile(uploadedFile);
    connection = await getPool().getConnection();
    const [[lockResult]] = await connection.query('SELECT GET_LOCK(?, 30) AS acquired', [
      contractPdfStorage.BACKUP_LOCK_NAME,
    ]);
    if (Number(lockResult.acquired) !== 1) {
      const error = new Error('Contract PDF storage is busy; try again');
      error.statusCode = 503;
      error.code = 'CONTRACT_STORAGE_BUSY';
      throw error;
    }
    storageLockAcquired = true;
    await connection.beginTransaction();

    const existing = await contractVersionRepository.getContractVersionById(normalizedId, connection, true);
    if (!existing) {
      throw createNotFoundError();
    }
    if (existing.status !== 'DRAFT' || existing.is_current) {
      throw createValidationError({ status: 'Only a DRAFT contract version can receive a PDF' });
    }
    previousStorageKey = existing.storage_path;

    storageKey = contractPdfStorage.createStorageKey();
    await contractPdfStorage.moveTemporaryFile(uploadedFile.path, storageKey);
    finalFileCreated = true;

    const updated = await contractVersionRepository.updateDraftPdf(
      normalizedId,
      { ...metadata, storage_path: storageKey },
      connection,
    );
    if (!updated) {
      throw createValidationError({ status: 'Only a DRAFT contract version can receive a PDF' });
    }

    commitAttempted = true;
    await connection.commit();
    committed = true;

    if (previousStorageKey && previousStorageKey !== storageKey) {
      try {
        await contractPdfStorage.removeStoredFile(previousStorageKey);
      } catch (error) {
        logError('Failed to remove replaced Draft contract PDF', {
          contractVersionId: normalizedId,
          code: error.code,
        });
      }
    }

    return { contract_version: normalizeContractVersion(
      await contractVersionRepository.getContractVersionById(normalizedId),
    ) };
  } catch (error) {
    if (commitAttempted && !committed) {
      logError('Contract PDF upload commit result is uncertain; stored file was retained for reconciliation', {
        contractVersionId: normalizedId,
        code: error.code,
      });
    }
    if (connection && !commitAttempted) {
      try {
        await connection.rollback();
      } catch (rollbackError) {
        logError('Failed to roll back Draft contract PDF upload', {
          contractVersionId: normalizedId,
          code: rollbackError.code,
        });
      }
    }
    if (finalFileCreated && !commitAttempted) {
      try {
        await contractPdfStorage.removeStoredFile(storageKey);
      } catch (cleanupError) {
        logError('Failed to clean up rejected Draft contract PDF', {
          contractVersionId: normalizedId,
          code: cleanupError.code,
        });
      }
    }
    throw error;
  } finally {
    if (connection) {
      if (storageLockAcquired) {
        try {
          await connection.query('SELECT RELEASE_LOCK(?)', [contractPdfStorage.BACKUP_LOCK_NAME]);
        } catch (error) {
          logError('Failed to release Contract PDF storage coordination lock', {
            contractVersionId: normalizedId,
            code: error.code,
          });
        }
      }
      connection.release();
    }
    if (uploadedFile && uploadedFile.path) {
      try {
        await contractPdfStorage.removeTemporaryFile(uploadedFile.path);
      } catch (cleanupError) {
        logError('Failed to clean up temporary contract PDF upload', {
          contractVersionId: normalizedId,
          code: cleanupError.code,
        });
      }
    }
  }
}

async function publishDraft(versionId) {
  const normalizedId = normalizeVersionId(versionId);
  return withTransaction(async (connection) => {
    const existing = await contractVersionRepository.getContractVersionById(normalizedId, connection, true);
    if (!existing) {
      throw createNotFoundError();
    }
    if (existing.status !== 'DRAFT' || existing.is_current) {
      throw createValidationError({ status: 'Only a DRAFT contract version can be published' });
    }

    const metadataErrors = validatePublishMetadata(existing);
    if (Object.keys(metadataErrors).length) {
      throw createValidationError(metadataErrors);
    }
    await contractPdfStorage.verifyStoredFile(existing);

    const published = await contractVersionRepository.publishDraft(normalizedId, connection);
    if (!published) {
      throw createValidationError({ status: 'Only a DRAFT contract version can be published' });
    }
    return { contract_version: normalizeContractVersion(
      await contractVersionRepository.getContractVersionById(normalizedId, connection),
    ) };
  });
}

async function deleteContractVersion(versionId) {
  const normalizedId = normalizeVersionId(versionId);
  const connection = await getPool().getConnection();
  let storageLockAcquired = false;
  let transactionStarted = false;
  let commitAttempted = false;
  let committed = false;
  let deletedVersion;
  let pdfCleanupWarning = false;

  try {
    const [[lockResult]] = await connection.query('SELECT GET_LOCK(?, 30) AS acquired', [
      contractPdfStorage.BACKUP_LOCK_NAME,
    ]);
    if (Number(lockResult.acquired) !== 1) {
      const error = new Error('Contract PDF storage is busy; try again');
      error.statusCode = 503;
      error.code = 'CONTRACT_STORAGE_BUSY';
      throw error;
    }
    storageLockAcquired = true;
    await connection.beginTransaction();
    transactionStarted = true;

    const existing = await contractVersionRepository.getContractVersionById(normalizedId, connection, true);
    if (!existing) {
      throw createNotFoundError();
    }
    if (existing.status !== 'DRAFT' && existing.status !== 'PUBLISHED') {
      throw createConflictError('CONTRACT_VERSION_CANNOT_BE_DELETED', '此契約版本狀態不可刪除');
    }
    if (existing.is_current) {
      throw createConflictError('CURRENT_CONTRACT_VERSION_CANNOT_BE_DELETED', '目前使用中的契約版本不可刪除');
    }

    const referenceCount = await contractVersionRepository.countContractVersionReferences(normalizedId, connection);
    if (referenceCount > 0) {
      throw createConflictError('CONTRACT_VERSION_IN_USE', '已被建檔或簽署紀錄引用的契約版本不可刪除');
    }

    const deleted = await contractVersionRepository.deleteContractVersion(normalizedId, connection);
    if (!deleted) {
      throw createNotFoundError();
    }
    deletedVersion = existing;
    commitAttempted = true;
    await connection.commit();
    committed = true;
    transactionStarted = false;

    if (deletedVersion.storage_path) {
      try {
        await contractPdfStorage.removeStoredFile(deletedVersion.storage_path);
      } catch (error) {
        pdfCleanupWarning = true;
        logError('Failed to remove deleted contract version PDF', {
          contractVersionId: normalizedId,
          code: error.code,
        });
      }
    }
  } catch (error) {
    if (commitAttempted && !committed) {
      logError('Contract version deletion commit result is uncertain; PDF was retained for reconciliation', {
        contractVersionId: normalizedId,
        code: error.code,
      });
    }
    if (transactionStarted) {
      try {
        await connection.rollback();
      } catch (rollbackError) {
        logError('Failed to roll back contract version deletion', {
          contractVersionId: normalizedId,
          code: rollbackError.code,
        });
      }
    }
    if (error.code === 'ER_ROW_IS_REFERENCED_2' || error.errno === 1451) {
      throw createConflictError('CONTRACT_VERSION_IN_USE', '已被建檔或簽署紀錄引用的契約版本不可刪除');
    }
    throw error;
  } finally {
    if (storageLockAcquired) {
      try {
        await connection.query('SELECT RELEASE_LOCK(?)', [contractPdfStorage.BACKUP_LOCK_NAME]);
      } catch (error) {
        logError('Failed to release Contract PDF storage coordination lock', {
          contractVersionId: normalizedId,
          code: error.code,
        });
      }
    }
    connection.release();
  }

  return { deleted: true, pdf_cleanup_warning: pdfCleanupWarning };
}

async function getContractVersionPdf(versionId) {
  const normalizedId = normalizeVersionId(versionId);
  const version = await contractVersionRepository.getContractVersionById(normalizedId);
  if (!version) {
    throw createNotFoundError();
  }
  if (version.status !== 'PUBLISHED') {
    throw createValidationError({ status: 'Only a PUBLISHED contract PDF can be viewed' });
  }
  return contractPdfStorage.verifyStoredFile(version);
}

async function setCurrent(versionId) {
  const normalizedId = normalizeVersionId(versionId);
  try {
    return await withTransaction(async (connection) => {
      const target = await contractVersionRepository.getContractVersionById(normalizedId, connection, true);
      if (!target) {
        throw createNotFoundError();
      }
      if (target.status !== 'PUBLISHED') {
        throw createValidationError({ status: 'Only a PUBLISHED contract version can be current' });
      }

      await contractVersionRepository.clearCurrent(connection, target.service_type);
      const marked = await contractVersionRepository.markCurrent(normalizedId, connection);
      if (!marked) {
        throw createValidationError({ status: 'Only a PUBLISHED contract version can be current' });
      }
      return { contract_version: await contractVersionRepository.getContractVersionById(normalizedId, connection) };
    });
  } catch (error) {
    if (error.code === 'ER_DUP_ENTRY' && String(error.message).includes('uq_contract_versions_current_slot')) {
      throw createConflictError('CURRENT_VERSION_CONFLICT', 'Another contract version is already current');
    }
    throw error;
  }
}

